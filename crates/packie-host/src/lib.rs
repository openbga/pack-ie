//! Hosting the Positive ACK engine as an OS service (`docs/requirements.md` ENG-01,
//! PKG-01; `docs/decisions.md` #2).
//!
//! - [`ServiceManager`] installs, removes, starts, stops and reports the service on each
//!   OS: launchd (macOS system daemon, or user agent when not root), systemd (Linux system
//!   unit with a dedicated `packie` user), [`windows`] (Windows service, with the state and
//!   log directories made private to SYSTEM and Administrators). [`platform`] returns the
//!   one for this OS.
//! - Every OS command goes through a [`Runner`], so tests use a scripted runner and never
//!   touch the real service manager.
//! - The service definitions (launchd plist, systemd unit) are generated by pure
//!   functions; the engine runs as `packie run --bootstrap <path> --service`.
//! - [`InstanceLock`] keeps one engine per state directory and records its pid, start
//!   time and bootstrap path for `status`.

