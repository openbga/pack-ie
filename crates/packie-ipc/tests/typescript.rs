//! Exports every IPC DTO to `console/src/ipc/generated/` and checks the result.
#![cfg(test)]

use std::path::PathBuf;

use packie_ipc::{ClientFrame, ServerFrame};
use ts_rs::TS;

#[test]
fn export_typescript_bindings() {
    let dir = PathBuf::from(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../console/src/ipc/generated"
    ));
    std::fs::create_dir_all(&dir).unwrap();
    // Regenerate from scratch so renamed or removed types do not linger.
    for entry in std::fs::read_dir(&dir).unwrap() {
        let path = entry.unwrap().path();
        if path.extension().is_some_and(|e| e == "ts") {
            std::fs::remove_file(path).unwrap();
        }
    }
    // JSON numbers arrive in JavaScript as `number`, so 64-bit counters are typed that way.
    let cfg = ts_rs::Config::new()
        .with_out_dir(&dir)
        .with_large_int("number");
    ClientFrame::export_all(&cfg).unwrap();
    ServerFrame::export_all(&cfg).unwrap();

    let mut names: Vec<String> = std::fs::read_dir(&dir)
        .unwrap()
        .filter_map(|e| {
            let name = e.unwrap().file_name().to_string_lossy().into_owned();
            name.strip_suffix(".ts").map(str::to_owned)
        })
        .collect();
    names.sort();
    let index: String = names
        .iter()
        .map(|name| format!("export type * from \"./{name}\";\n"))
        .collect();
    std::fs::write(
        dir.join("index.ts"),
        format!("// Generated by `cargo test -p packie-ipc`; do not edit.\n{index}"),
    )
    .unwrap();

    for expected in [
        "Request",
        "Response",
        "Event",
        "EngineSnapshot",
        "RuntimeConfig",
        "LogFilter",
    ] {
        assert!(
            names.iter().any(|n| n == expected),
            "{expected} not exported: {names:?}"
        );
    }
    let request = std::fs::read_to_string(dir.join("Request.ts")).unwrap();
    assert!(request.contains("document: RuntimeConfig"), "{request}");
    assert!(!request.contains("bigint"), "{request}");
}
